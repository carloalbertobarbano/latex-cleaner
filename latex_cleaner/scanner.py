"""Dependency scanner.

Starting from one or more root documents, the scanner follows the
references found in the (comment-free) source and collects every file of
the project that is needed to compile them.

Paths are resolved the way TeX does it: relative to the directory of the
root document (TeX's working directory), with ``\\import``/``\\subimport``
and ``\\graphicspath`` changing the search base. The directory of the file
that contains the reference is used as a fallback.
"""

from __future__ import annotations

import os
import posixpath
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

from . import lexer

# files that are parsed for further references
TEXT_EXTS = {".tex", ".sty", ".cls", ".tikz", ".pgf", ".ltx", ".def", ".cfg",
             ".clo", ".bbx", ".cbx", ".lbx"}
# pdflatex lookup order (graphicx with pdftex.def), followed by formats
# used by other engines
GRAPHICS_EXTS = [".pdf", ".png", ".jpg", ".mps", ".jpeg", ".jbig2", ".jb2",
                 ".PDF", ".PNG", ".JPG", ".JPEG", ".JBIG2", ".JB2", ".eps",
                 ".ps", ".svg"]
GENERIC_EXTS = GRAPHICS_EXTS + [".tex", ".csv", ".dat", ".txt", ".tsv"]
# files generated by auxiliary tools that must be shipped next to a root
COMPANION_EXTS = [".bbl", ".ind", ".gls", ".nls"]
ALWAYS_KEEP = ["00README", "00README.XXX", "00README.json", "00README.yaml"]

# command name -> (kind, number of required args, index of the path arg,
#                  extensions tried, comma-separated list?, warn if missing?)
@dataclass(frozen=True)
class Spec:
    kind: str
    nargs: int = 1
    path_arg: int = 0
    exts: tuple = ("",)
    comma: bool = False
    warn: bool = True
    prefix: str = ""
    # how the path is written back when flattening: "always" with the
    # extension, "never" (LaTeX adds it), or as in the "original" text
    ext: str = "original"


INPUT_EXTS = (".tex", "")
SPECS: dict[str, Spec] = {
    "input": Spec("input", exts=INPUT_EXTS, ext="always"),
    "include": Spec("input", exts=(".tex",), ext="never"),
    "subfile": Spec("input", exts=INPUT_EXTS, ext="always"),
    "subfileinclude": Spec("input", exts=INPUT_EXTS, ext="always"),
    "InputIfFileExists": Spec("input", exts=INPUT_EXTS, ext="always", warn=False),
    "includestandalone": Spec("standalone", exts=INPUT_EXTS, ext="never"),
    "loadglsentries": Spec("input", exts=INPUT_EXTS, ext="always"),
    "import": Spec("import", nargs=2, path_arg=1, exts=INPUT_EXTS, ext="always"),
    "subimport": Spec("subimport", nargs=2, path_arg=1, exts=INPUT_EXTS, ext="always"),
    "inputfrom": Spec("import", nargs=2, path_arg=1, exts=INPUT_EXTS, ext="always"),
    "includefrom": Spec("import", nargs=2, path_arg=1, exts=(".tex",), ext="never"),
    "subinputfrom": Spec("subimport", nargs=2, path_arg=1, exts=INPUT_EXTS, ext="always"),
    "subincludefrom": Spec("subimport", nargs=2, path_arg=1, exts=(".tex",), ext="never"),
    "includegraphics": Spec("graphics", exts=("",) + tuple(GRAPHICS_EXTS), ext="always"),
    "includesvg": Spec("graphics", exts=(".svg", ""), ext="never"),
    "includepdf": Spec("graphics", exts=(".pdf", "")),
    "pgfimage": Spec("graphics", exts=("",) + tuple(GRAPHICS_EXTS), ext="always"),
    "includemedia": Spec("graphics", nargs=2, path_arg=1, warn=False),
    "bibliography": Spec("bib", exts=(".bib",), comma=True, ext="never"),
    "nobibliography": Spec("bib", exts=(".bib",), comma=True, ext="never"),
    "addbibresource": Spec("bib"),
    "addglobalbib": Spec("bib"),
    "bibliographystyle": Spec("pkg", exts=(".bst",), warn=False, ext="never"),
    "usepackage": Spec("pkg", exts=(".sty",), comma=True, warn=False, ext="never"),
    "RequirePackage": Spec("pkg", exts=(".sty",), comma=True, warn=False, ext="never"),
    "RequirePackageWithOptions": Spec("pkg", exts=(".sty",), warn=False, ext="never"),
    "documentclass": Spec("pkg", exts=(".cls",), warn=False, ext="never"),
    "LoadClass": Spec("pkg", exts=(".cls",), warn=False, ext="never"),
    "LoadClassWithOptions": Spec("pkg", exts=(".cls",), warn=False, ext="never"),
    "usetheme": Spec("theme", exts=(".sty",), comma=True, warn=False, prefix="beamertheme"),
    "usecolortheme": Spec("theme", exts=(".sty",), comma=True, warn=False, prefix="beamercolortheme"),
    "usefonttheme": Spec("theme", exts=(".sty",), comma=True, warn=False, prefix="beamerfonttheme"),
    "useinnertheme": Spec("theme", exts=(".sty",), comma=True, warn=False, prefix="beamerinnertheme"),
    "useoutertheme": Spec("theme", exts=(".sty",), comma=True, warn=False, prefix="beameroutertheme"),
    "lstinputlisting": Spec("listing"),
    "verbatiminput": Spec("listing"),
    "VerbatimInput": Spec("listing"),
    "BVerbatimInput": Spec("listing"),
    "LVerbatimInput": Spec("listing"),
    "inputminted": Spec("listing", nargs=2, path_arg=1),
    "graphicspath": Spec("graphicspath"),
    "ProvidesPackage": Spec("provides", warn=False),
    "ProvidesClass": Spec("provides", warn=False),
    "ProvidesFile": Spec("provides", warn=False),
}

_cmd_re = re.compile(r"\\(" + "|".join(sorted(SPECS, key=len, reverse=True)) + r")(?![A-Za-z@])")
_generic_re = re.compile(r"\{([^{}\\\s%#$&^]+)\}")


@dataclass
class Ref:
    """A reference to a file found in the source."""
    src: str          # file containing the reference (relative to the project root)
    start: int        # span of the path text in the original file content
    end: int
    text: str         # path text as written
    target: str       # resolved file (relative to the project root)
    kind: str
    line: int
    rewrite: bool = True   # may be rewritten when flattening
    ext: str = "original"  # see Spec.ext


@dataclass
class MacroPath:
    """A path built from a macro argument, such as ``figs/#1``.

    When flattening, the literal directory prefix (``figs/``) is removed."""
    src: str
    start: int
    end: int          # span of the directory prefix
    directory: str    # resolved directory (relative to the project root)
    line: int


@dataclass
class Edit:
    """A fixed replacement used when flattening (e.g. drop ``\\graphicspath``)."""
    src: str
    start: int
    end: int
    replacement: str


@dataclass
class Plan:
    root_dir: Path
    roots: list[str]
    keep: set[str] = field(default_factory=set)
    refs: list[Ref] = field(default_factory=list)
    edits: list[Edit] = field(default_factory=list)
    companions: dict[str, str] = field(default_factory=dict)  # companion -> root
    warnings: list[str] = field(default_factory=list)
    unresolved_flatten: list[str] = field(default_factory=list)
    macro_paths: list[MacroPath] = field(default_factory=list)

    def warn(self, msg: str) -> None:
        if msg not in self.warnings:
            self.warnings.append(msg)


# --------------------------------------------------------------------------
# helpers

def read_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8", errors="surrogateescape")


def _norm(p: str) -> str:
    p = posixpath.normpath(p.replace("\\", "/"))
    return "" if p == "." else p


class _FS:
    """Case-exact file lookups inside the project (macOS is case-insensitive,
    arXiv builds on Linux which is not)."""

    def __init__(self, root: Path):
        self.root = root
        self._listing: dict[str, dict[str, str]] = {}

    def _list(self, rel_dir: str) -> dict[str, str]:
        if rel_dir not in self._listing:
            d = self.root / rel_dir if rel_dir else self.root
            try:
                names = os.listdir(d)
            except OSError:
                names = []
            self._listing[rel_dir] = {n.lower(): n for n in names} | {n: n for n in names}
        return self._listing[rel_dir]

    def lookup(self, rel: str) -> tuple[str | None, bool]:
        """Return (on-disk relative path, exact case?) or (None, False)."""
        rel = _norm(rel)
        if not rel or rel.startswith("../") or rel == "..":
            return None, False
        parts = rel.split("/")
        cur = ""
        exact = True
        for k, part in enumerate(parts):
            listing = self._list(cur)
            if part in listing and listing[part] == part:
                name = part
            elif part.lower() in listing:
                name = listing[part.lower()]
                exact = False
            else:
                return None, False
            cur = f"{cur}/{name}" if cur else name
        if not (self.root / cur).is_file():
            return None, False
        return cur, exact


@lru_cache(maxsize=None)
def _in_tex_distribution(name: str) -> bool:
    exe = shutil.which("kpsewhich")
    if not exe:
        return False
    try:
        out = subprocess.run([exe, name], capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return bool(out.stdout.strip())


def _skip_ws(s: str, j: int) -> int:
    n = len(s)
    while j < n and s[j] in " \t\n":
        # do not cross a paragraph break
        if s[j] == "\n" and s.find("\n", j + 1) == j + 1:
            break
        j += 1
    return j


def parse_args(masked: str, j: int, nargs: int) -> tuple[list[tuple[int, int]], list[tuple[int, int]], int] | None:
    """Parse ``*``, optional ``[..]``/``<..>`` groups and ``nargs`` brace groups.

    Returns (required arg content spans, optional arg content spans, end) or None.
    """
    n = len(masked)
    if j < n and masked[j] == "*":
        j += 1
    req: list[tuple[int, int]] = []
    opt: list[tuple[int, int]] = []
    while len(req) < nargs:
        j = _skip_ws(masked, j)
        if j >= n:
            return None
        c = masked[j]
        if c == "[" and not req:
            e = lexer._find_matching_bracket(masked, j)
            if e < 0:
                return None
            opt.append((j + 1, e))
            j = e + 1
        elif c == "<" and not req:
            e = masked.find(">", j)
            if e < 0:
                return None
            j = e + 1
        elif c == "{":
            e = lexer._find_matching_brace(masked, j)
            if e < 0:
                return None
            req.append((j + 1, e))
            j = e + 1
        else:
            return None
    return req, opt, j


def _comma_items(text: str, a: int, b: int) -> list[tuple[int, int]]:
    items = []
    pos = a
    for piece in text[a:b].split(","):
        lead = len(piece) - len(piece.lstrip())
        s = pos + lead
        e = s + len(piece.strip())
        if e > s:
            items.append((s, e))
        pos += len(piece) + 1
    return items


def _graphicspath_dirs(text: str) -> list[str]:
    dirs = re.findall(r"\{([^{}]*)\}", text)
    if not dirs and text.strip():
        dirs = [text.strip()]
    return [d.strip() for d in dirs]


# --------------------------------------------------------------------------

def find_roots(root_dir: Path) -> list[str]:
    """All ``.tex`` files of the project that contain ``\\begin{document}``."""
    roots = []
    for dirpath, dirnames, filenames in os.walk(root_dir):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for fn in sorted(filenames):
            if not fn.lower().endswith((".tex", ".ltx")):
                continue
            p = Path(dirpath) / fn
            try:
                masked = lexer.mask(read_text(p))
            except OSError:
                continue
            if re.search(r"\\begin\s*\{document\}", masked):
                roots.append(p.relative_to(root_dir).as_posix())
    return roots


class Scanner:
    def __init__(self, root_dir: Path, roots: list[str]):
        self.root_dir = root_dir
        self.fs = _FS(root_dir)
        self.plan = Plan(root_dir=root_dir, roots=list(roots))
        self._visited: set = set()
        self._texts: dict[str, tuple[str, str]] = {}
        self._ref_index: dict[tuple[str, int], str] = {}
        self._uses_bib: set[str] = set()

    # -- file access ----------------------------------------------------
    def text_of(self, rel: str) -> tuple[str, str]:
        if rel not in self._texts:
            text = read_text(self.root_dir / rel)
            is_tex = Path(rel).suffix.lower() in (".tex", ".ltx", ".tikz")
            self._texts[rel] = (text, lexer.mask(text, cut_end_document=is_tex))
        return self._texts[rel]

    def resolve(self, arg: str, bases: list[str], exts) -> tuple[str | None, bool]:
        arg = arg.strip()
        if not arg:
            return None, False
        seen = set()
        # TeX tries each extension on the whole search path before the next one
        for ext in exts:
            for base in bases:
                cand = _norm(posixpath.join(base, arg + ext))
                if cand in seen:
                    continue
                seen.add(cand)
                found, exact = self.fs.lookup(cand)
                if found:
                    return found, exact
        return None, False

    # -- main entry -----------------------------------------------------
    def run(self) -> Plan:
        for root in self.plan.roots:
            found, exact = self.fs.lookup(root)
            if not found:
                self.plan.warn(f"root document not found: {root}")
                continue
            root_dir = posixpath.dirname(found)
            ctx = {"root": found, "root_dir": root_dir, "graphicspath": []}
            self.plan.keep.add(found)
            self.scan_file(found, root_dir, ctx)
            stem = posixpath.splitext(found)[0]
            for ext in COMPANION_EXTS:
                comp, _ = self.fs.lookup(stem + ext)
                if comp:
                    self.plan.keep.add(comp)
                    self.plan.companions[comp] = found
            if found in self._uses_bib and not self.fs.lookup(stem + ".bbl")[0]:
                self.plan.warn(
                    f"{found}: uses a bibliography but {stem}.bbl was not found; "
                    "arXiv needs the .bbl file (compile the paper locally first)")
        for name in ALWAYS_KEEP:
            found, _ = self.fs.lookup(name)
            if found:
                self.plan.keep.add(found)
        return self.plan

    # -- scanning -------------------------------------------------------
    def _add_ref(self, src, text, a, b, target, exact, kind, rewrite=True, ext="original"):
        line = text.count("\n", 0, a) + 1
        key = (src, a)
        prev = self._ref_index.get(key)
        if prev is not None:
            if prev != target:
                self.plan.warn(
                    f"{src}:{line}: '{text[a:b]}' resolves to both {prev} and {target} "
                    "(file reached from different documents); flattening uses the first")
            return
        self._ref_index[key] = target
        self.plan.refs.append(Ref(src, a, b, text[a:b], target, kind, line, rewrite, ext))
        self.plan.keep.add(target)
        if not exact:
            self.plan.warn(
                f"{src}:{line}: '{text[a:b]}' matches '{target}' only ignoring case; "
                "this fails on case-sensitive systems such as arXiv's")

    def _missing(self, src, text, a, arg, spec: Spec, kind_label: str):
        if not spec.warn:
            return
        if spec.kind == "input" and _in_tex_distribution(arg if "." in posixpath.basename(arg) else arg + ".tex"):
            return
        line = text.count("\n", 0, a) + 1
        if "#" in arg and Path(src).suffix.lower() not in (".tex", ".ltx", ".tikz"):
            return
        if "#" in arg:
            self.plan.warn(f"{src}:{line}: {kind_label} '{arg}' is built from a macro argument "
                           "and cannot be followed; add the files with --keep")
            return
        self.plan.warn(f"{src}:{line}: {kind_label} '{arg}' not found")

    def scan_file(self, rel: str, base: str, ctx: dict) -> None:
        key = (ctx["root_dir"], rel, base, tuple(ctx["graphicspath"]))
        if key in self._visited:
            return
        self._visited.add(key)
        if Path(rel).suffix.lower() not in TEXT_EXTS:
            return
        try:
            text, masked = self.text_of(rel)
        except OSError as e:
            self.plan.warn(f"cannot read {rel}: {e}")
            return
        file_dir = posixpath.dirname(rel)
        root_dir = ctx["root_dir"]
        consumed: list[tuple[int, int]] = []

        events = []
        for m in _cmd_re.finditer(masked):
            events.append(m)

        for m in events:
            name = m.group(1)
            spec = SPECS[name]
            if name == "input":
                # \input file  (TeX primitive syntax without braces)
                j = _skip_ws(masked, m.end())
                if j < len(masked) and masked[j] != "{":
                    mm = re.compile(r"[^\s{}%\\]+").match(masked, j)
                    if mm:
                        consumed.append((m.start(), mm.end()))
                        self._handle_input(rel, text, mm.start(), mm.end(), base, root_dir, file_dir, ctx, spec)
                    continue
            parsed = parse_args(masked, m.end(), spec.nargs)
            if parsed is None:
                continue
            req, opt, end = parsed
            consumed.append((m.start(), end))

            if spec.kind == "graphicspath":
                a, b = req[0]
                dirs = _graphicspath_dirs(text[a:b])
                ctx["graphicspath"] = [_norm(posixpath.join(base, d)) for d in dirs]
                # remove the whole line when the command is alone on it
                ls = text.rfind("\n", 0, m.start()) + 1
                le = text.find("\n", end)
                le = len(text) if le < 0 else le
                if text[ls:m.start()].strip() == "" and masked[end:le].strip() == "":
                    self.plan.edits.append(Edit(rel, ls, min(le + 1, len(text)), ""))
                else:
                    self.plan.edits.append(Edit(rel, m.start(), end, ""))
                continue

            if name == "documentclass" and opt:
                cls = text[req[0][0]:req[0][1]].strip()
                if cls == "subfiles":
                    a, b = opt[0]
                    oa, ob = a + (len(text[a:b]) - len(text[a:b].lstrip())), b - (len(text[a:b]) - len(text[a:b].rstrip()))
                    target, exact = self.resolve(text[oa:ob], [file_dir, base], INPUT_EXTS)
                    if target:
                        self._add_ref(rel, text, oa, ob, target, exact, "subfiles-main")

            a, b = req[spec.path_arg]
            items = _comma_items(text, a, b) if spec.comma else [(a + len(text[a:b]) - len(text[a:b].lstrip()),
                                                                   b - (len(text[a:b]) - len(text[a:b].rstrip())))]
            for ia, ib in items:
                arg = text[ia:ib]
                if not arg:
                    continue
                if spec.kind == "provides":
                    # \ProvidesPackage{styles/foo} must match the flattened name
                    if "/" in arg:
                        self._add_ref(rel, text, ia, ib, rel, True, "provides")
                    continue
                if "#" in arg:
                    self._macro_path(rel, text, ia, arg, spec, base, root_dir, ctx, name)
                    continue
                if spec.kind in ("import", "subimport"):
                    da, db = req[0]
                    d = text[da:db].strip()
                    new_base = _norm(posixpath.join(base if spec.kind == "subimport" else root_dir, d)) \
                        if not posixpath.isabs(d) else None
                    if new_base is None:
                        self.plan.warn(f"{rel}: absolute path in \\{name}{{{d}}} cannot be shipped")
                        continue
                    target, exact = self.resolve(arg, [new_base], spec.exts)
                    if not target:
                        self._missing(rel, text, ia, posixpath.join(d, arg), spec, f"\\{name}")
                        continue
                    self._add_ref(rel, text, ia, ib, target, exact, spec.kind, ext=spec.ext)
                    self.plan.edits.append(Edit(rel, da, db, "./"))
                    self.scan_file(target, new_base, ctx)
                    continue
                if spec.kind in ("input", "standalone"):
                    self._handle_input(rel, text, ia, ib, base, root_dir, file_dir, ctx, spec)
                    continue
                if spec.kind == "graphics":
                    bases = [base, root_dir] + ctx["graphicspath"] + [file_dir]
                    target, exact = self.resolve(arg, bases, spec.exts)
                    if target:
                        self._add_ref(rel, text, ia, ib, target, exact, "graphics", ext=spec.ext)
                        if Path(target).suffix.lower() in TEXT_EXTS:
                            self.scan_file(target, base, ctx)
                    else:
                        self._missing(rel, text, ia, arg, spec, "graphics file")
                    continue
                if spec.kind == "bib":
                    self._uses_bib.add(ctx["root"])
                    target, exact = self.resolve(arg, [root_dir, base, file_dir], spec.exts)
                    if target:
                        self._add_ref(rel, text, ia, ib, target, exact, "bib", ext=spec.ext)
                    else:
                        self._missing(rel, text, ia, arg, spec, "bibliography file")
                    continue
                if spec.kind == "theme":
                    target, exact = self.resolve(spec.prefix + arg, [root_dir, base, file_dir], spec.exts)
                    if target:
                        self._add_ref(rel, text, ia, ib, target, exact, "theme", rewrite=False)
                        self.scan_file(target, base, ctx)
                    continue
                # pkg, listing
                bases = [root_dir, base, file_dir] if spec.kind == "pkg" else [base, root_dir, file_dir]
                target, exact = self.resolve(arg, bases, spec.exts)
                if target:
                    self._add_ref(rel, text, ia, ib, target, exact, spec.kind, ext=spec.ext)
                    if spec.kind == "pkg":
                        self.scan_file(target, base, ctx)
                else:
                    self._missing(rel, text, ia, arg, spec, f"\\{name} file")

        self._scan_generic(rel, text, masked, consumed, base, root_dir, file_dir, ctx)

    def _macro_path(self, rel, text, ia, arg, spec, base, root_dir, ctx, name):
        """Record the literal directory of a path such as ``figs/#1``."""
        line = text.count("\n", 0, ia) + 1
        prefix = arg[:arg.index("#")]
        directory = None
        if "/" in prefix:
            dpart = prefix[:prefix.rindex("/") + 1]
            for b in [base, root_dir] + ctx["graphicspath"]:
                cand = _norm(posixpath.join(b, dpart))
                if cand and (self.root_dir / cand).is_dir():
                    directory = cand
                    break
            if directory is not None:
                self.plan.macro_paths.append(MacroPath(rel, ia, ia + len(dpart), directory, line))
        if Path(rel).suffix.lower() not in (".tex", ".ltx", ".tikz"):
            return  # macro code in packages/classes is not about project files
        where = f" (files in {directory}/)" if directory else ""
        self.plan.warn(f"{rel}:{line}: \\{name}{{{arg}}} is built from a macro argument and "
                       f"cannot be followed; add the files it uses{where} with --keep")

    def _handle_input(self, rel, text, ia, ib, base, root_dir, file_dir, ctx, spec):
        arg = text[ia:ib].strip()
        target, exact = self.resolve(arg, [base, root_dir, file_dir], spec.exts)
        if not target:
            self._missing(rel, text, ia, arg, spec, "input file")
            return
        self._add_ref(rel, text, ia, ib, target, exact, spec.kind, ext=spec.ext)
        if spec.kind == "standalone":
            # the compiled figure may be used instead of the source
            stem = posixpath.splitext(target)[0]
            for ext in (".pdf", ".png", ".svg"):
                comp, _ = self.fs.lookup(stem + ext)
                if comp:
                    self.plan.keep.add(comp)
        self.scan_file(target, base, ctx)

    def _scan_generic(self, rel, text, masked, consumed, base, root_dir, file_dir, ctx):
        """Keep files named in brace groups of unknown commands (e.g. data
        files used by pgfplots or paths passed to user macros)."""
        consumed.sort()
        for m in _generic_re.finditer(masked):
            a, b = m.start(1), m.end(1)
            if any(s <= a < e for s, e in consumed):
                continue
            before = masked[max(0, m.start() - 12):m.start()]
            if re.search(r"\\(begin|end)\s*$", before):
                continue
            arg = text[a:b]
            pathlike = "/" in arg
            exts = ("",) + (tuple(GENERIC_EXTS) if pathlike else ())
            target, exact = self.resolve(arg, [base, root_dir, file_dir], exts)
            if not target:
                if (pathlike and Path(rel).suffix.lower() in (".tex", ".ltx", ".tikz")
                        and re.fullmatch(r"\.{0,2}/?[\w.+-]+(/[\w.+-]+)+/?", arg)):
                    self.plan.unresolved_flatten.append(
                        f"{rel}:{text.count(chr(10), 0, a) + 1}: '{arg}'")
                continue
            rewrite = pathlike or "." in arg
            self._add_ref(rel, text, a, b, target, exact, "generic", rewrite=rewrite)
            if Path(target).suffix.lower() in TEXT_EXTS:
                self.scan_file(target, base, ctx)


def scan(root_dir: Path, roots: list[str]) -> Plan:
    return Scanner(root_dir, roots).run()
